#!/usr/bin/env bash
# Prints backend/.env from environment variables (set by the deploy workflow from
# GitHub Environment secrets/vars). Empty values are left out so the backend's
# defaults (src/config/env.ts) apply. Fails if a required value is missing, so a
# deploy can never overwrite the server's .env with a broken one.
set -euo pipefail

required=(DATABASE_URL JWT_SECRET JWT_REFRESH_SECRET)
optional=(PORT API_URL FRONTEND_URL ADMIN_URL PAYMENT_PROVIDER PAYMENT_SECRET
  RAZORPAY_KEY_ID RAZORPAY_KEY_SECRET RAZORPAY_WEBHOOK_SECRET
  JWT_EXPIRES_IN JWT_REFRESH_EXPIRES_IN BOOKING_HOLD_MINUTES
  RATE_LIMIT_WINDOW_MS RATE_LIMIT_MAX UPLOAD_DIR MAX_UPLOAD_MB LOG_LEVEL)

missing=()
for v in "${required[@]}"; do [ -n "${!v:-}" ] || missing+=("$v"); done
if [ "${PAYMENT_PROVIDER:-mock}" = "razorpay" ]; then
  for v in RAZORPAY_KEY_ID RAZORPAY_KEY_SECRET RAZORPAY_WEBHOOK_SECRET; do
    [ -n "${!v:-}" ] || missing+=("$v")
  done
fi
if [ ${#missing[@]} -gt 0 ]; then
  echo "Missing GitHub secrets: ${missing[*]}" >&2
  exit 1
fi

echo "# Generated by GitHub Actions - edit the GitHub Environment secrets, not this file."
echo "NODE_ENV=production"
for v in "${required[@]}" "${optional[@]}"; do
  val="${!v:-}"
  [ -z "$val" ] && continue
  case "$val" in *$'\n'*) echo "$v contains a newline" >&2; exit 1 ;; esac
  # Single-quote so spaces/#/$ survive dotenv; a value containing ' is written raw.
  case "$val" in
    *"'"*) printf '%s=%s\n' "$v" "$val" ;;
    *) printf "%s='%s'\n" "$v" "$val" ;;
  esac
done
